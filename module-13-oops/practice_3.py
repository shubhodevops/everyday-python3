# একটি ক্লাস তৈরি করা:

class Rectangle(): # একটি ক্লাস 'Rectangle' তৈরি করা হলো
    
    def __init__(self, l,h): # ইনস্ট্যান্স ভেরিয়েবলগুলো সচল করার জন্য কনস্ট্রাক্টর মেথড
        self.length = l # ইনস্ট্যান্স ভেরিয়েবল
        self.height = h # ইনস্ট্যান্স ভেরিয়েবল
    def area(self): # ইনস্ট্যান্স মেথড অবশ্যই প্রথম প্যারামিটার হিসেবে 'self' দিয়ে সংজ্ঞায়িত করতে হবে
        return self.length * self.height # আয়তক্ষেত্রের ক্ষেত্রফল রিটার্ন করবে

    def perimeter(self): # ইনস্ট্যান্স মেথড অবশ্যই প্রথম প্যারামিটার হিসেবে 'self' দিয়ে সংজ্ঞায়িত করতে হবে
        return 2*(self.length + self.height) # আয়তক্ষেত্রের পরিসীমা রিটার্ন করবে

# ক্লাসের একটি অবজেক্ট বা ইনস্ট্যান্স তৈরি করা

s=Rectangle(10,5) # Rectangle ক্লাসের ইনস্ট্যান্স বা অবজেক্ট
area=s.area() # Rectangle ক্লাসের area মেথডকে কল করা
perimeter=s.perimeter() # Rectangle ক্লাসের perimeter মেথডকে কল করা

print(f"Rectangle area is {area}") # আয়তক্ষেত্রের ক্ষেত্রফল প্রিন্ট করা
print(f"Rectangle perimeter is {perimeter}") # আয়তক্ষেত্রের পরিসীমা প্রিন্ট করা

# অবজেক্টের নাম এবং ডট (.) অপারেটর ব্যবহার করে ক্লাসের ভেরিয়েবলগুলো অ্যাক্সেস করা যায়
print(f"Length of rectangle is {s.length}") # আয়তক্ষেত্রের দৈর্ঘ্য প্রিন্ট করা  
print(f"Height of rectangle is {s.height}") # আয়তক্ষেত্রের উচ্চতা প্রিন্ট করা  

