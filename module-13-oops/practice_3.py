# পাইথনে ক্লাস এবং অবজেক্টের ধারণা বোঝার জন্য অবজেক্ট ওরিয়েন্টেড প্রোগ্রামিংয়ের জ্ঞান থাকা গুরুত্বপূর্ণ------------------------


# অবজেক্ট ওরিয়েন্টেড প্রোগ্রামিংয়ের তত্ত্বটি অবজেক্ট এবং ক্লাসের ধারণার উপর ভিত্তি করে তৈরি
# অবজেক্ট ওরিয়েন্টেড প্রোগ্রামিং হলো এমন একটি প্রোগ্রামিং প্যারাডাইম (পদ্ধতি) যা প্রোগ্রাম ডিজাইন এবং বাস্তবায়নের জন্য অবজেক্ট এবং ক্লাস ব্যবহার করে 

# ক্লাস হলো অবজেক্টের একটি ব্লুপ্রিন্ট (নকশা) এবং অবজেক্ট হলো ক্লাসের একটি ইনস্ট্যান্স (বাস্তব রূপ)
# অবজেক্ট হলো একটি ক্লাসের ইনস্ট্যান্স যার নিজস্ব স্টেট (অবস্থা) এবং বিহেভিয়ার (আচরণ) থাকে
# অবজেক্ট এবং ইনস্ট্যান্স একই জিনিস এবং এগুলো একে অপরের পরিপূরক হিসেবে ব্যবহার করা যায়
# এনক্যাপসুলেশন হলো ডাটা এবং মেথডগুলোকে ক্লাস নামক একটি একক ইউনিটের মধ্যে একসাথে গুটিয়ে রাখার ধারণা
# অ্যাবস্ট্রাকশন হলো কোড কীভাবে কাজ করছে তার ভেতরের জটিল বিবরণ লুকিয়ে রেখে ব্যবহারকারীকে কেবল মূল কার্যকারিতা দেখানোর ধারণা
# ডাটা হাইডিং হলো ক্লাসের ভেতরের গুরুত্বপূর্ণ ডাটা বা ভেরিয়েবল বাইরের সরাসরি অ্যাক্সেস থেকে সুরক্ষিত রাখা, যা সাধারণত প্রাইভেট মেম্বার (যেমন পাইথনে ডাবল আন্ডারস্কোর __ ব্যবহার করে) তৈরির মাধ্যমে করা হয়


# ক্লাসের ভেরিয়েবল তিন প্রকার হতে পারে: ইনস্ট্যান্স ভেরিয়েবল (instance variable), ক্লাস ভেরিয়েবল (class variable) এবং লোকাল ভেরিয়েবল (local variable)
# ক্লাসের মেথড তিন প্রকার হতে পারে: ইনস্ট্যান্স মেথড (instance method), ক্লাস মেথড (class method) এবং স্ট্যাটিক মেথড (static method)

# ইনস্ট্যান্স ভেরিয়েবল হলো এমন একটি ভেরিয়েবল যা কনস্ট্রাক্টর মেথডের ভেতরে সংজ্ঞায়িত করা হয় এবং এটি ক্লাসের প্রতিটি ইনস্ট্যান্স বা অবজেক্টের জন্য আলাদা ও অনন্য হয়
# ইনস্ট্যান্স মেথড হলো এমন একটি মেথড যা ক্লাসের ভেতরে সংজ্ঞায়িত করা হয় এবং এটি ক্লাসের প্রতিটি ইনস্ট্যান্সের জন্য অনন্য। এটি প্রথম প্যারামিটার হিসেবে 'self' গ্রহণ করে, যা ক্লাসের নিজস্ব ইনস্ট্যান্সকে নির্দেশ করে

# ক্লাস ভেরিয়েবল হলো এমন একটি ভেরিয়েবল যা ক্লাসের ভেতরে সংজ্ঞায়িত করা হয় এবং এটি ক্লাসের সব ইনস্ট্যান্স বা অবজেক্টের মধ্যে ভাগাভাগি (share) করা হয়
# ক্লাস মেথড হলো এমন একটি মেথড যা ক্লাসের ভেতরে সংজ্ঞায়িত করা হয় এবং এটি ক্লাসের সব ইনস্ট্যান্সের মধ্যে ভাগাভাগি করা হয়। এটি @classmethod ডেকোরেটর ব্যবহার করে সংজ্ঞায়িত করা হয় এবং প্রথম প্যারামিটার হিসেবে 'cls' গ্রহণ করে, যা ক্লাসটিকে নিজেকেই নির্দেশ করে

# লোকাল ভেরিয়েবল হলো এমন একটি ভেরিয়েবল যা কোনো মেথডের ভেতরে সংজ্ঞায়িত করা হয় এবং এটি কেবল সেই মেথডের জন্যই নির্দিষ্ট থাকে। এই মেথডের বাইরে থেকে এটিকে অ্যাক্সেস বা ব্যবহার করা যায় না

# স্ট্যাটিক ভেরিয়েবল হলো এমন একটি ভেরিয়েবল যা ক্লাসের ভেতরে সংজ্ঞায়িত করা হয় এবং ক্লাসের সব ইনস্ট্যান্সের মধ্যে ভাগাভাগি করা হয়। এটি @staticmethod ডেকোরেটর ব্যবহার করে সংজ্ঞায়িত করা হয় এবং এটি প্রথম প্যারামিটার হিসেবে 'self' বা 'cls' কোনোটিই গ্রহণ করে না। এটিকে ক্লাসের নাম বা অবজেক্টের নাম ব্যবহার করে কল করা যায়

# স্ট্যাটিক মেথড হলো এমন একটি মেথড যা ক্লাসের ভেতরে সংজ্ঞায়িত করা হয় এবং ক্লাসের সব ইনস্ট্যান্সের মধ্যে ভাগাভাগি করা হয়। এটি @staticmethod ডেকোরেটর ব্যবহার করে সংজ্ঞায়িত করা হয় এবং এটি প্রথম প্যারামিটার হিসেবে 'self' বা 'cls' কোনোটিই গ্রহণ করে না। এটিকে ক্লাসের নাম বা অবজেক্টের নাম ব্যবহার করে কল করা যায়


# 'self' হলো ক্লাসের বর্তমান ইনস্ট্যান্স বা অবজেক্টের একটি রেফারেন্স (নির্দেশক) এবং এটি ক্লাসের ইনস্ট্যান্স ভেরিয়েবল ও মেথডগুলো অ্যাক্সেস করতে ব্যবহৃত হয়      
# কনস্ট্রাক্টর (constructor) হলো একটি বিশেষ মেথড যা ক্লাসের কোনো অবজেক্ট তৈরি করার সময় স্বয়ংক্রিয়ভাবে কল হয় এবং এটি ক্লাসের ইনস্ট্যান্স ভেরিয়েবলগুলোকে সচল (initialize) করতে ব্যবহৃত হয়

# প্রপার্টি মেথড (property method) ডট ডট অপারেটর ব্যবহার না করেই ক্লাসের ইনস্ট্যান্স ভেরিয়েবলগুলো অ্যাক্সেস করতে ব্যবহৃত হয়। এটি @property ডেকোরেটর ব্যবহার করে সংজ্ঞায়িত করা হয় এবং এটি ডট অপারেটর ব্যবহার না করেই ক্লাসের ইনস্ট্যান্স ভেরিয়েবলগুলো অ্যাক্সেস করতে ব্যবহৃত হয়। (দ্রষ্টব্য: প্রপার্টি মেথড মূলত অবজেক্টের মেথডকে ভেরিয়েবলের মতো করে অ্যাক্সেস করতে সাহায্য করে)

# ডেকোরেটর (decorators) কোনো মেথড বা ফাংশনের আচরণ পরিবর্তন বা মডিফাই করতে ব্যবহৃত হয়। এগুলো '@' চিহ্নের পর ডেকোরেটরের নাম লিখে সংজ্ঞায়িত করা হয় এবং এগুলো কোনো মেথড বা ফাংশনের আচরণ পরিবর্তন করতে ব্যবহৃত হয়।

# def __init__ হলো একটি বিশেষ মেথড যা ক্লাসের কোনো অবজেক্ট তৈরি করার সময় কল হয় এবং এটি ক্লাসের ইনস্ট্যান্স ভেরিয়েবলগুলোকে সচল করতে ব্যবহৃত হয়। এটি 'def' কিওয়ার্ডের পর মেথডের নাম লিখে সংজ্ঞায়িত করা হয় এবং এটি প্রথম প্যারামিটার হিসেবে 'self' গ্রহণ করে, যা ক্লাসের নিজস্ব ইনস্ট্যান্সকে নির্দেশ করে।
