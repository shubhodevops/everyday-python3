# এই প্রজেক্টে টার্গেট ফিচারগুলো যেভাবে কাজ করছে:
# input() ফাংশন: শিক্ষার্থীর নাম, রোল এবং ৩টি বিষয়ের নম্বর সরাসরি ইউজারের কাছ থেকে ডাইনামিকালি ইনপুট নেওয়া হচ্ছে।
#
# Python List (student_database): এটি একটি সেন্ট্রাল ডাটাবেজ হিসেবে কাজ করছে। লুপের প্রতিটি ইটারেশনে তৈরি হওয়া শিক্ষার্থীর ডিকশনারিটি .append() এর মাধ্যমে এই লিস্টে জমা হচ্ছে।
#
# Python Dictionary (student_info): একজন নির্দিষ্ট শিক্ষার্থীর বিভিন্ন ক্যাটাগরির তথ্য (Name, Roll, Average, Grade) কী-ভ্যালু (Key: Value) পেয়ার আকারে গুছিয়ে রাখার জন্য এটি ব্যবহৃত হয়েছে।
#
# Loops (for i in range(...)): ইউজার শুরুতে যে কয়জন শিক্ষার্থীর সংখ্যা ইনপুট দেবেন, ঠিক ততবার ইনপুট নেওয়ার প্রক্রিয়াটি রিপিট বা লুপ করার জন্য এটি ব্যবহৃত হয়েছে। শেষে ফলাফল দেখানোর জন্যও আরেকটি লুপ ব্যবহার করা হয়েছে।
#
# Conditional Logic (if-elif-else): গড় নম্বরের ওপর ভিত্তি করে একজন শিক্ষার্থী কী গ্রেড (A+, A, B, Pass, Fail) পাবে, তা স্বয়ংক্রিয়ভাবে নির্ধারণ করতে এই কন্ডিশনাল লজিক ব্যবহার করা হয়েছে।


# শিক্ষার্থীর ডাটা জমা রাখার জন্য খালি লিস্ট (List of Dictionaries)
student_database = []

print("=== স্টুডেন্ট গ্রেডিং সিস্টেমে স্বাগতম ===")

# ব্যবহারকারী কয়জন শিক্ষার্থীর ডাটা ইনপুট দিতে চান তা নির্ধারণ (Loop-এর জন্য)
total_students = int(input("কতজন শিক্ষার্থীর তথ্য ইনপুট দিতে চান? : "))

# ১. লুপ (Loop) ব্যবহার করে প্রতি শিক্ষার্থীর তথ্য নেওয়া
for i in range(total_students):
    print(f"\n--- {i+1} নম্বর শিক্ষার্থীর তথ্য দিন ---")

    # input() ফাংশন দিয়ে ইউজার ইনপুট নেওয়া
    name = input("শিক্ষার্থীর নাম: ")
    roll = input("রোল নম্বর: ")

    # নম্বর ইনপুট নিয়ে সেগুলোকে Integer-এ রূপান্তর করা
    bangla = int(input("বাংলায় প্রাপ্ত নম্বর: "))
    english = int(input("ইংরেজিতে প্রাপ্ত নম্বর: "))
    math = int(input("গণিতে প্রাপ্ত নম্বর: "))

    # গড় নম্বর হিসাব করা
    average_mark = (bangla + english + math) / 3

    # ২. কন্ডিশনাল লজিক (Conditional Logic) দিয়ে গ্রেড নির্ধারণ
    if average_mark >= 80:
        grade = "A+"
    elif average_mark >= 70:
        grade = "A"
    elif average_mark >= 60:
        grade = "B"
    elif average_mark >= 40:
        grade = "Pass"
    else:
        grade = "Fail"

    # ৩. ডিকশনারি (Dictionary) তৈরি করে শিক্ষার্থীর সব ডাটা সাজানো
    student_info = {
        "Name": name,
        "Roll": roll,
        "Average": round(average_mark, 2),
        "Grade": grade,
    }

    # ৪. লিস্ট (List)-এর ভেতরে ডিকশনারিটি পুশ বা অ্যাপেন্ড করা
    student_database.append(student_info)

# --- ডাটা প্রদর্শন অংশ ---
print("\n====================================")
print("     সকল শিক্ষার্থীর চূড়ান্ত ফলাফল     ")
print("====================================")

# লিস্টের ভেতর থেকে লুপ চালিয়ে ডাটা সুন্দরভাবে প্রিন্ট করা
for student in student_database:
    print(
        f"রোল: {student['Roll']} | নাম: {student['Name']} | গড় নম্বর: {student['Average']} | গ্রেড: {student['Grade']}"
    )

print("====================================")
