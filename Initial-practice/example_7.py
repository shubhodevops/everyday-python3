# 📖 ব্যাখ্যা (বাংলায়)
# লিস্ট → এখানে students নামের লিস্টে সব ছাত্রের তথ্য রাখা হচ্ছে।
#
# ডিকশনারি → প্রতিটি ছাত্রের নাম, রোল, গ্রেড আলাদা key-value pair আকারে রাখা হয়েছে।
#
# লুপ → for লুপ ব্যবহার করে একাধিক ছাত্রের তথ্য নেওয়া হচ্ছে এবং আবার দেখানো হচ্ছে।
#
# কন্ডিশনাল লজিক → if-elif-else দিয়ে গ্রেড অনুযায়ী আলাদা বার্তা দেখানো হচ্ছে।
#
# 🎯 বাস্তব জীবনের ব্যবহার
# এই প্রজেক্টটি ব্যবহার করে:
#
# স্কুলে ছাত্রদের তথ্য সংরক্ষণ করা যায়।
#
# অফিসে কর্মচারীদের তথ্য রাখা যায়।
#
# শপিং লিস্ট বা ইনভেন্টরি ম্যানেজমেন্টেও একইভাবে ব্যবহার করা যায়।


# ছাত্রদের তথ্য রাখার জন্য লিস্ট
students = []

# ব্যবহারকারীর কাছ থেকে কতজন ছাত্রের তথ্য নেওয়া হবে
n = int(input("কতজন ছাত্রের তথ্য দিতে চান? "))

# লুপ চালিয়ে তথ্য সংগ্রহ
for i in range(n):
    name = input(f"{i+1} নম্বর ছাত্রের নাম লিখুন: ")
    roll = input(f"{i+1} নম্বর ছাত্রের রোল লিখুন: ")
    grade = input(f"{i+1} নম্বর ছাত্রের গ্রেড লিখুন: ")

    # ডিকশনারি দিয়ে একেকজন ছাত্রের তথ্য রাখা
    student = {
        "নাম": name,
        "রোল": roll,
        "গ্রেড": grade
    }

    # লিস্টে ডিকশনারি যোগ করা
    students.append(student)

# সব ছাত্রের তথ্য দেখানো
print("\n--- ছাত্রদের তথ্য ---")
for s in students:
    print(f"নাম: {s['নাম']}, রোল: {s['রোল']}, গ্রেড: {s['গ্রেড']}")

# কন্ডিশনাল লজিক: গ্রেড অনুযায়ী বার্তা দেখানো
print("\n--- ফলাফল বিশ্লেষণ ---")
for s in students:
    if s["গ্রেড"] == "A+":
        print(f"{s['নাম']} অসাধারণ করেছে! 🎉")
    elif s["গ্রেড"] == "B":
        print(f"{s['নাম']} ভালো করেছে, আরও চেষ্টা করো।")
    else:
        print(f"{s['নাম']} কে আরও পড়াশোনা করতে হবে।")
